test('packing checks use latest state, preserve trip items and reject stale and malformed entries',()=>{
  const original = itemData();
  assert.equal(saveHoneymoonPackingItem(original,null,{title:'새 준비물'},'new-packing').honeymoon.packing[0].done,false);
  let data = saveHoneymoonPackingItem(original,null,{title:'  여권  ',done:false},'passport');
  assert.equal(data.honeymoon.items,original.honeymoon.items);
  assert.equal(data.honeymoon.packing[0].title,'여권');
  const before = structuredClone(data);
  const checked = toggleHoneymoonPackingItem(data,'passport');
  assert.equal(checked.honeymoon.packing[0].done,true);
  assert.equal(toggleHoneymoonPackingItem(checked,'passport').honeymoon.packing[0].done,false);
  assert.deepEqual(data,before);
  assert.equal(honeymoonSummary(checked).packed,1);
  assert.throws(()=>saveHoneymoonPackingItem(data,null,{title:'신분증',done:false},'passport'),/이미 존재/);
  for (const mutation of [{title:''},{title:' '},{title:'x'.repeat(101)},{done:1},{done:undefined}]) assert.throws(()=>saveHoneymoonPackingItem(data,'passport',mutation));
  assert.equal(validHoneymoon({...data.honeymoon,packing:[data.honeymoon.packing[0],data.honeymoon.packing[0]]}),false);
  const deleted = deleteHoneymoonPackingItem(data,'passport');
  assert.equal(deleted.honeymoon.packing.length,0);
  assert.equal(deleted.honeymoon.items,data.honeymoon.items);
  assert.throws(()=>toggleHoneymoonPackingItem(deleted,'passport'),/삭제된 준비물/);
  assert.throws(()=>saveHoneymoonPackingItem(deleted,'passport',{title:'여권'}),/삭제된 준비물/);
  assert.equal(deleteHoneymoonPackingItem(data,'missing'),data);
});
