test('latest reservation links survive edits and deleted records cannot be resurrected by stale updates',()=>{
  const original = itemData();
  const linked = linkHoneymoonItemToBudget(original,'ubud');
  const next = saveHoneymoonItem(linked,'ubud',{title:'우붓에서 3박',expenseId:'stale-link'});
  assert.equal(next.honeymoon.items[0].expenseId,'trip-ubud');
  assert.equal(next.expenses,linked.expenses);
  assert.equal(original.honeymoon.items[0].title,fields.title);
  assert.equal(original.honeymoon.items[0].expenseId,'');
  assert.equal(original.expenses.length,0);
  assert.equal(updateHoneymoonItemStatus(next,'ubud','예약 완료').honeymoon.items[0].status,'예약 완료');
  assert.throws(()=>updateHoneymoonItemStatus(next,'ubud','취소'));
  assert.throws(()=>saveHoneymoonItem(next,null,fields,'ubud'),/이미 존재/);
  const deleted = deleteHoneymoonItem(next,'ubud');
  assert.throws(()=>saveHoneymoonItem(deleted,'ubud',fields),/삭제된 여행/);
  assert.throws(()=>updateHoneymoonItemStatus(deleted,'ubud','이용 완료'),/삭제된 여행/);
  assert.throws(()=>linkHoneymoonItemToBudget(deleted,'ubud'),/삭제된 여행/);
  assert.equal(deleteHoneymoonItem(original,'missing'),original);
  assert.equal(saveHoneymoonItem(initialData,null,{...fields,expenseId:'fake-link'},'new').honeymoon.items[0].expenseId,'');
});
