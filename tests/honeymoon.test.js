test('old backups expose an empty Bali plan without saving templates or changing stored data',()=>{
  const data = structuredClone(initialData);
  delete data.honeymoon;
  const before = structuredClone(data);
  assert.deepEqual(getHoneymoon(data),empty);
  assert.deepEqual(honeymoonSummary(data),{budget:0,planned:0,confirmed:0,projected:0,available:0,count:0,reserved:0,completed:0,linked:0,packingTotal:0,packed:0});
  assert.deepEqual(data,before);
  assert.equal(validHoneymoon(getHoneymoon(data)),true);
  assert.equal(validBackup(data),true);
  assert.equal(validBackup({...data,honeymoon:null}),false);
  assert.equal(validBackup({...data,honeymoon:{...empty,budget:-1}}),false);
  const view = getHoneymoon(data);
  view.items.push({id:'not-stored'});
  assert.deepEqual(getHoneymoon(data),empty);
  assert.ok(honeymoonCategories.includes(fields.category));
  assert.ok(honeymoonStatuses.includes(fields.status));
});
