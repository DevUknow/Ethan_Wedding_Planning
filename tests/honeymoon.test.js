test('budget links guard paid amounts and unrelated IDs and fabricate no payments for planned expenses',()=>{
  let data = savePayment(linkHoneymoonItemToBudget(itemData({actualAmount:850000}),'ubud'),'trip-ubud',payment);
  assert.throws(()=>linkHoneymoonItemToBudget(saveHoneymoonItem(data,'ubud',{actualAmount:50000}),'ubud'),/이미 결제/);
  assert.throws(()=>linkHoneymoonItemToBudget(saveHoneymoonItem(data,'ubud',{actualAmount:null}),'ubud'),/이미 결제/);
  assert.equal(expenseTotals(data.expenses[0]).paid,100000);
  const collision = {...itemData(),expenses:[{...data.expenses[0],honeymoonItemId:'another'}]};
  assert.throws(()=>linkHoneymoonItemToBudget(collision,'ubud'),/다른 항목/);
  const noMarker = {...itemData(),expenses:[{...data.expenses[0],honeymoonItemId:undefined}]};
  assert.throws(()=>linkHoneymoonItemToBudget(noMarker,'ubud'),/다른 항목/);
  let sharedId = saveHoneymoonItem(itemData(),null,{...fields,title:'다른 숙소'},'another');
  sharedId = {...sharedId,honeymoon:{...sharedId.honeymoon,items:sharedId.honeymoon.items.map(item => item.id==='another' ? {...item,expenseId:'trip-ubud'} : item)}};
  assert.throws(()=>linkHoneymoonItemToBudget(sharedId,'ubud'),/다른 항목/);
  assert.equal(validHoneymoon({...sharedId.honeymoon,items:sharedId.honeymoon.items.map(item => ({...item,expenseId:'trip-ubud'}))}),false);
  const planned = linkHoneymoonItemToBudget(itemData(),'ubud');
  assert.equal(planned.expenses[0].actualAmount,null);
  assert.equal(expenseTotals(planned.expenses[0]).paid,0);
  const recreated = linkHoneymoonItemToBudget({...planned,expenses:[]},'ubud');
  assert.equal(recreated.expenses.length,1);
  assert.equal(recreated.expenses[0].id,'trip-ubud');
  assert.deepEqual(recreated.expenses[0].payments,[]);
  const longest = saveHoneymoonItem(initialData,null,{...fields,title:'x'.repeat(100)},'a'.repeat(95));
  assert.equal(linkHoneymoonItemToBudget(longest,'a'.repeat(95)).expenses[0].id.length,100);
  assert.equal(linkHoneymoonItemToBudget(longest,'a'.repeat(95)).expenses[0].title.length,100);
  assert.throws(()=>saveHoneymoonItem(initialData,null,fields,'a'.repeat(96)));
});
